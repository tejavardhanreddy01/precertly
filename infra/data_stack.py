"""precertly-data: the Aurora Serverless v2 database and the tools task that works on it.

Depends on precertly-app (its VPC and subnets); precertly-app never refers to this stack.

The database is Aurora PostgreSQL, one `db.serverless` writer in the isolated subnets, scaled to
zero: with a minimum capacity of 0 it pauses after 5 minutes without a client connection, so
the idle cost is storage (plus the secret). It holds synthetic data that can be rebuilt, so
everything is removed with the stack: no final snapshot, no deletion protection, one day of
backups.

The tools task (family `precertly-tools`) is the API image with a command chosen at `run-task`:
migrations, ingest, a read-only check. It has no service and no desired count; it is started
and stopped by scripts/deploy.sh. It runs in the public subnets with a public IP, because the
VPC has no NAT or endpoints, and reaches the database over the VPC's local route.

The later DB-enabled API service (names.API_LIVE_SERVICE) will live here too, so this stack
never has to be referenced from precertly-app. Nothing defines it yet.
"""

import json
from typing import Any

import aws_cdk as cdk
from aws_cdk import Aws, aws_ec2, aws_ecr, aws_ecs, aws_iam, aws_logs, aws_rds, aws_secretsmanager
from constructs import Construct

import names
from app_stack import BEDROCK_PROFILE_ID, EMBEDDING_MODEL_ID
from precertly_stack import PrecertlyStack

# Aurora PostgreSQL 16.13: the newest 16.x in the pinned aws-cdk-lib. The CDK does NOT check
# that a version supports auto-pause (a minimum capacity of 0 synthesizes for any version); the
# AWS docs say 16.3 or later. The AWS release notes list pgvector 0.8.1 for 16.13 (HNSW needs
# 0.5.0 or later). Neither is verified against a running cluster.
AURORA_POSTGRES_VERSION = aws_rds.AuroraPostgresEngineVersion.VER_16_13
DB_PORT = 5432
DB_NAME = "precertly"
DB_USER = "precertly"
MIN_ACU = 0
MAX_ACU = 2
# The shortest the service allows (the L2 rejects less).
AUTO_PAUSE_SECONDS = 300
BACKUP_RETENTION_DAYS = 1
DB_CONNECT_TIMEOUT_SECONDS = 60

TOOLS_CPU = 512
TOOLS_MEMORY_MIB = 1024

# The secret's JSON keys and the settings they feed (src/precertly/settings.py; a test compares
# these names with that file). host and port are added by the secret's attachment to the cluster.
SECRET_FIELD_TO_ENV = {
    "host": "PRECERTLY_DB_HOST",
    "port": "PRECERTLY_DB_PORT",
    "username": "PRECERTLY_DB_USER",
    "password": "PRECERTLY_DB_PASSWORD",
    "dbname": "PRECERTLY_DB_NAME",
}


class DataStack(PrecertlyStack):
    def __init__(
        self,
        scope: Construct,
        construct_id: str,
        *,
        image_tag: str,
        vpc: aws_ec2.IVpc,
        database_subnets: aws_ec2.SubnetSelection,
        tools_subnets: aws_ec2.SubnetSelection,
        **kwargs: Any,
    ) -> None:
        super().__init__(scope, construct_id, **kwargs)
        self.tools_security_group = aws_ec2.SecurityGroup(
            self,
            "ToolsSecurityGroup",
            vpc=vpc,
            description="Tools task: no inbound rules, all outbound",
            allow_all_outbound=True,
        )
        self.database_security_group = aws_ec2.SecurityGroup(
            self,
            "DatabaseSecurityGroup",
            vpc=vpc,
            description="Database: port 5432 from the tools task only, no outbound",
            allow_all_outbound=False,
        )
        self.database_security_group.add_ingress_rule(
            self.tools_security_group,
            aws_ec2.Port.tcp(DB_PORT),
            "PostgreSQL from the tools task",
        )
        self.secret = self._secret()
        self.cluster = self._cluster(vpc, database_subnets)
        self.log_group = aws_logs.LogGroup(
            self,
            "ToolsLogGroup",
            log_group_name=names.TOOLS_LOG_GROUP,
            retention=aws_logs.RetentionDays.ONE_WEEK,
            removal_policy=cdk.RemovalPolicy.DESTROY,
        )
        repository = aws_ecr.Repository.from_repository_name(self, "Repository", names.ECR_REPO)
        self.task_definition = self._tools_task(repository, image_tag)
        self._outputs(vpc, tools_subnets)

    def _secret(self) -> aws_secretsmanager.Secret:
        # Defined here, not generated by the cluster, so that it carries `dbname` as well. No
        # fixed name: a deleted secret stays scheduled for deletion for days, and a fixed name
        # would block re-creating the stack. Punctuation is excluded so the password is safe in
        # a URL and in a shell without quoting.
        return aws_secretsmanager.Secret(
            self,
            "DatabaseSecret",
            description="Precertly database credentials (username, password, dbname, host, port)",
            generate_secret_string=aws_secretsmanager.SecretStringGenerator(
                secret_string_template=json.dumps({"username": DB_USER, "dbname": DB_NAME}),
                generate_string_key="password",
                exclude_punctuation=True,
                password_length=32,
            ),
            removal_policy=cdk.RemovalPolicy.DESTROY,
        )

    def _cluster(
        self, vpc: aws_ec2.IVpc, database_subnets: aws_ec2.SubnetSelection
    ) -> aws_rds.DatabaseCluster:
        return aws_rds.DatabaseCluster(
            self,
            "Database",
            engine=aws_rds.DatabaseClusterEngine.aurora_postgres(version=AURORA_POSTGRES_VERSION),
            credentials=aws_rds.Credentials.from_secret(self.secret),
            default_database_name=DB_NAME,
            writer=aws_rds.ClusterInstance.serverless_v2("writer", publicly_accessible=False),
            serverless_v2_min_capacity=MIN_ACU,
            serverless_v2_max_capacity=MAX_ACU,
            serverless_v2_auto_pause_duration=cdk.Duration.seconds(AUTO_PAUSE_SECONDS),
            enable_data_api=False,
            vpc=vpc,
            vpc_subnets=database_subnets,
            security_groups=[self.database_security_group],
            storage_encrypted=True,
            backup=aws_rds.BackupProps(retention=cdk.Duration.days(BACKUP_RETENTION_DAYS)),
            deletion_protection=False,
            removal_policy=cdk.RemovalPolicy.DESTROY,
        )

    def _tools_task(
        self, repository: aws_ecr.IRepository, image_tag: str
    ) -> aws_ecs.FargateTaskDefinition:
        execution_role = aws_iam.Role(
            self,
            "ToolsExecutionRole",
            role_name=names.TOOLS_EXECUTION_ROLE,
            assumed_by=aws_iam.ServicePrincipal("ecs-tasks.amazonaws.com"),
        )
        task_role = aws_iam.Role(
            self,
            "ToolsTaskRole",
            role_name=names.TOOLS_TASK_ROLE,
            assumed_by=aws_iam.ServicePrincipal("ecs-tasks.amazonaws.com"),
        )
        # Embeddings only: the tools never call a chat model. Titan is called in-region.
        task_role.add_to_policy(
            aws_iam.PolicyStatement(
                sid="EmbeddingsInvoke",
                actions=["bedrock:InvokeModel"],
                resources=[
                    self.format_arn(
                        service="bedrock",
                        resource=f"foundation-model/{EMBEDDING_MODEL_ID}",
                        region=Aws.REGION,
                        account="",
                    )
                ],
            )
        )
        task_definition = aws_ecs.FargateTaskDefinition(
            self,
            "ToolsTaskDefinition",
            family=names.TOOLS_FAMILY,
            cpu=TOOLS_CPU,
            memory_limit_mib=TOOLS_MEMORY_MIB,
            runtime_platform=aws_ecs.RuntimePlatform(
                cpu_architecture=aws_ecs.CpuArchitecture.ARM64,
                operating_system_family=aws_ecs.OperatingSystemFamily.LINUX,
            ),
            task_role=task_role,
            execution_role=execution_role,
        )
        # The cluster's own attached secret, so the task depends on the attachment that adds
        # host and port. No command or entrypoint: scripts/deploy.sh sets one per run.
        attached = self.cluster.secret
        assert attached is not None
        task_definition.add_container(
            names.TOOLS_CONTAINER,
            image=aws_ecs.ContainerImage.from_ecr_repository(repository, image_tag),
            environment={
                "PRECERTLY_AWS_REGION": Aws.REGION,
                # Empty: use the task role, not the local named profile the setting defaults to.
                "PRECERTLY_AWS_PROFILE": "",
                "PRECERTLY_BEDROCK_MODEL_ID": BEDROCK_PROFILE_ID,
                "PRECERTLY_EMBEDDING_MODEL_ID": EMBEDDING_MODEL_ID,
                # No idle connection may keep the database awake; a resume can take a while.
                "PRECERTLY_DB_POOL": "null",
                "PRECERTLY_DB_CONNECT_TIMEOUT": str(DB_CONNECT_TIMEOUT_SECONDS),
            },
            secrets={
                env: aws_ecs.Secret.from_secrets_manager(attached, field)
                for field, env in SECRET_FIELD_TO_ENV.items()
            },
            logging=aws_ecs.LogDrivers.aws_logs(stream_prefix="tools", log_group=self.log_group),
        )
        return task_definition

    def _outputs(self, vpc: aws_ec2.IVpc, tools_subnets: aws_ec2.SubnetSelection) -> None:
        subnet_ids = vpc.select_subnets(subnet_type=tools_subnets.subnet_type).subnet_ids
        cdk.CfnOutput(self, "ClusterIdentifier", value=self.cluster.cluster_identifier)
        cdk.CfnOutput(self, "SecretArn", value=self.secret.secret_arn)
        cdk.CfnOutput(self, "ToolsSubnetIds", value=cdk.Fn.join(",", subnet_ids))
        cdk.CfnOutput(
            self, "ToolsSecurityGroupId", value=self.tools_security_group.security_group_id
        )
        cdk.CfnOutput(self, "ToolsLogGroupName", value=self.log_group.log_group_name)
