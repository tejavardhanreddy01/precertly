"""Build the live API contract fixture the web tests read.

    uv run python scripts/build_live_contract.py           # write the fixture
    uv run python scripts/build_live_contract.py --check   # fail if the committed file is stale

The fixture holds one RunState per status, one failed or rejected state per reason, a Started
response, and the enum values, all produced by the real Pydantic models in
src/precertly/live/models.py. A model change therefore fails tests/test_live_contract.py until
the fixture is rebuilt, and the web tests (web/src/lib/live/contract.test.ts) parse the fixture
with the web's own runtime guards, so the TypeScript side fails when the fixture changes.

Synthetic values only: the ids and quotes are made up and no chart text is copied.
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import UTC, datetime
from pathlib import Path
from typing import get_args

from precertly.live.models import (
    MESSAGES,
    NOTICE,
    LiveChecklistItem,
    LiveCitation,
    LiveResult,
    LiveVerdict,
    Reason,
    RunState,
    RunStatus,
    Started,
)

FIXTURE = (
    Path(__file__).resolve().parents[1] / "web" / "src" / "lib" / "live" / "contract.fixture.json"
)

RUN_ID = "00000000-0000-4000-8000-000000000001"
STARTED_AT = datetime(2026, 1, 2, 3, 4, 5, tzinfo=UTC)
FINISHED_AT = datetime(2026, 1, 2, 3, 5, 35, tzinfo=UTC)
TIMINGS = {
    "waking_database": 0.5,
    "checking_limits": 0.1,
    "ingesting": 12.25,
    "judging": 40.0,
}
# Statuses a run has already left, for each status it can be in.
ORDER = [
    RunStatus.WAKING_DATABASE,
    RunStatus.CHECKING_LIMITS,
    RunStatus.INGESTING,
    RunStatus.JUDGING,
]
REJECTED_REASONS = {
    Reason.RUN_IN_PROGRESS,
    Reason.DAILY_CAP_TOTAL,
    Reason.DAILY_CAP_USER,
    Reason.DAILY_TOKENS,
}


def _result() -> LiveResult:
    return LiveResult(
        case_id="facet-01",
        policy="example-policy",
        variant="example-variant",
        overall="insufficient",
        verdicts=[
            LiveVerdict(
                criterion="example-criterion-a",
                outcome="met",
                applicable=True,
                decided_by="model",
                confidence=0.75,
                rationale="The note states the finding. <b>Markup in a rationale is text.</b>",
                citations=[
                    LiveCitation(
                        chunk_id="DocumentReference/example-note#0",
                        quote="example quote from a synthetic note",
                        char_start=10,
                        char_end=44,
                    )
                ],
            ),
            LiveVerdict(
                criterion="example-criterion-b",
                outcome="met",
                applicable=False,
                decided_by="rule",
                confidence=1.0,
                rationale="The condition does not apply.",
                citations=[],
            ),
            LiveVerdict(
                criterion="example-criterion-c",
                outcome="insufficient",
                applicable=True,
                decided_by="rule+model",
                confidence=0.25,
                rationale="Nothing in the chart settles it.",
                citations=[],
            ),
        ],
        reviewer_checklist=[
            LiveChecklistItem(
                criterion="example-criterion-d",
                evidence_stage="provider_attestation",
                text="Confirm the attestation with the provider.",
            )
        ],
        input_tokens=12000,
        output_tokens=3400,
        latency_ms=41250.5,
    )


def _state(status: RunStatus, reason: Reason | None = None) -> RunState:
    finished = status.finished
    left = (
        {s.value: TIMINGS[s.value] for s in ORDER[: ORDER.index(status)]}
        if status in ORDER
        else dict(TIMINGS)
    )
    return RunState(
        run_id=RUN_ID,
        case_id="facet-01",
        status=status,
        reason=reason,
        message=MESSAGES[reason] if reason else None,
        started_at=STARTED_AT,
        finished_at=FINISHED_AT if finished else None,
        timings=left,
        result=_result() if status is RunStatus.DONE else None,
    )


def build() -> dict[str, object]:
    """The fixture, as plain JSON values."""

    def dump(model: RunState | Started) -> dict[str, object]:
        return model.model_dump(mode="json")

    ended = []
    for reason in Reason:
        status = RunStatus.REJECTED if reason in REJECTED_REASONS else RunStatus.FAILED
        ended.append(dump(_state(status, reason)))
    return {
        "note": (
            "Generated by scripts/build_live_contract.py from src/precertly/live/models.py. "
            "Do not edit."
        ),
        "notice": NOTICE,
        "enums": {
            "statuses": [s.value for s in RunStatus],
            "reasons": [r.value for r in Reason],
            "outcomes": list(get_args(LiveVerdict.model_fields["outcome"].annotation)),
            "decided_by": list(get_args(LiveVerdict.model_fields["decided_by"].annotation)),
        },
        "messages": {r.value: text for r, text in MESSAGES.items()},
        "started": dump(Started(run_id=RUN_ID, status=RunStatus.WAKING_DATABASE)),
        "run_states": {
            s.value: dump(_state(s))
            for s in RunStatus
            if s not in (RunStatus.FAILED, RunStatus.REJECTED)
        },
        "ended_states": ended,
    }


def render() -> str:
    return json.dumps(build(), indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check", action="store_true", help="fail if the committed fixture is stale"
    )
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        current = FIXTURE.read_text() if FIXTURE.exists() else ""
        if current != text:
            print(
                f"{FIXTURE} is stale: run `uv run python scripts/build_live_contract.py`",
                file=sys.stderr,
            )
            return 1
        print("live contract fixture is current")
        return 0
    FIXTURE.write_text(text)
    print(f"wrote {FIXTURE}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
